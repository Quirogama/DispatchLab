const languageKey = 'dispatchlab.language';
const themeKey = 'dispatchlab.theme';
let currentLanguage = localStorage.getItem(languageKey) || 'en';

export function t(value) {
    return translations[currentLanguage][value] || translations.en[value] || value;
}

export function currentLocale() {
    return currentLanguage;
}

function replaceTextNodes(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => {
        const value = node.nodeValue.trim();
        if (!value) return;
        const key = Object.keys(translations.en).find(candidate =>
            candidate === value ||
            translations.en[candidate] === value ||
            Object.values(translations).some(language => language[candidate] === value)
        );
        if (!key || !translations[currentLanguage][key]) return;
        const leading = node.nodeValue.match(/^\s*/)[0];
        const trailing = node.nodeValue.match(/\s*$/)[0];
        node.nodeValue = `${leading}${translations[currentLanguage][key]}${trailing}`;
    });
}

function updateControls() {
    document.querySelectorAll('[data-language]').forEach(button => {
        button.classList.toggle('active', button.dataset.language === currentLanguage);
    });
    const theme = document.documentElement.dataset.theme || 'dark';
    document.querySelectorAll('[data-theme]').forEach(button => {
        button.classList.toggle('active', button.dataset.theme === theme);
    });
}

export function applyLanguage(language = currentLanguage) {
    currentLanguage = translations[language] ? language : 'en';
    localStorage.setItem(languageKey, currentLanguage);
    document.documentElement.lang = currentLanguage;
    replaceTextNodes(document.body);
    updateControls();
    document.dispatchEvent(new CustomEvent('dispatchlab:language', { detail: currentLanguage }));
}

export function applyTheme(theme = localStorage.getItem(themeKey) || 'dark') {
    const selectedTheme = theme === 'light' ? 'light' : 'dark';
    document.documentElement.dataset.theme = selectedTheme;
    localStorage.setItem(themeKey, selectedTheme);
    updateControls();
    document.dispatchEvent(new CustomEvent('dispatchlab:theme', { detail: selectedTheme }));
}

document.addEventListener('click', event => {
    const languageButton = event.target.closest('[data-language]');
    const themeButton = event.target.closest('[data-theme]');
    if (languageButton) applyLanguage(languageButton.dataset.language);
    if (themeButton) applyTheme(themeButton.dataset.theme);
});

applyTheme();
applyLanguage();
